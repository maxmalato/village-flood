export const messages: Record<Locale, Record<MessageKey, string>> = { 'pt-BR': ptBR, en }

/** Escolhe o idioma a partir das preferências do navegador. PT-BR é o padrão. */
export function pickLocale(preferred: readonly string[]): Locale {
  for (const tag of preferred) {
    const lower = tag.toLowerCase()
    if (lower.startsWith('pt')) return 'pt-BR'
    if (lower.startsWith('en')) return 'en'
  }
  return 'pt-BR'
}

export type Params = Record<string, string | number>

/** Devolve o texto da chave no idioma pedido, trocando {nome} pelos parâmetros. */
export function t(locale: Locale, key: MessageKey, params: Params = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

/** Nomes dos parâmetros usados num texto ({nome}). */
export function paramsOf(text: string): string[] {
  return [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1] ?? '').sort()
}
